import mongoose from 'mongoose'
import { env } from './env'

/**
 * The application's single MongoDB connection.
 *
 * Mongoose keeps one global connection pool, so every model registered anywhere
 * in the app shares this connection rather than opening its own.
 *
 * Note there is no schema migration step in this design: the Mongoose schemas
 * are the source of truth for structure and indexes, and `npm run db:indexes`
 * reconciles the database to them via `syncIndexes()`. See the README for the
 * trade-off this accepts (no ordered rollback history).
 */

/**
 * Reject unknown operators in query filters rather than silently ignoring them.
 * Without this, a typo such as `{ featured: { $eqq: true } }` would match
 * everything instead of erroring.
 */
mongoose.set('strictQuery', 'throw')

/**
 * Fail a query that waits too long for a connection instead of buffering it
 * indefinitely. Without this, an Atlas outage or a missing IP allowlist entry
 * makes requests hang until the client gives up, rather than returning a 500.
 */
mongoose.set('bufferTimeoutMS', 10_000)

if (env.isDevelopment) {
  // Logs every query — useful for spotting an accidental N+1 while building.
  mongoose.set('debug', (collection: string, method: string, query: unknown) => {
    console.log(`[mongo] ${collection}.${method}`, JSON.stringify(query))
  })
}

/**
 * Turns a driver connection failure into specific, actionable guidance.
 *
 * These failure modes look almost identical from the outside but have entirely
 * different fixes, and guessing wrong costs a lot of time. Written as a
 * function rather than one catch-all message so the operator is pointed at the
 * one thing that is actually wrong.
 */
export function describeConnectionError(error: unknown): string[] {
  const err = error as { name?: string; code?: number | string; message?: string } | null
  const message = err?.message ?? ''

  // Atlas rejects bad credentials with error code 8000 / "bad auth".
  if (err?.code === 8000 || /bad auth|Authentication failed/i.test(message)) {
    return [
      'MongoDB rejected the username or password (Atlas error 8000).',
      'The network, TLS and IP allowlist are all FINE — the connection reached Atlas',
      'and Atlas refused the credentials. Check, in Atlas > Database Access:',
      '  1. A database user with exactly that username exists in THIS project',
      '  2. Its password matches the one in MONGODB_URI — if it was autogenerated,',
      '     it is shown only once, so use "Edit > Reset Password" to set a known one',
      '  3. The user is not restricted to a different cluster',
      '  4. Any of @ : / ? # [ ] % in the password must be percent-encoded in the URI',
    ]
  }

  // Could not reach any node — this is the one that usually IS the allowlist.
  if (err?.name === 'MongoServerSelectionError') {
    return [
      'Could not reach any MongoDB server before the timeout.',
      '  1. Add this machine\'s current IP in Atlas > Network Access',
      '  2. Check the cluster is not paused (free tier pauses after inactivity)',
      '  3. Check a firewall or VPN is not blocking outbound port 27017',
    ]
  }

  if (err?.name === 'MongoParseError') {
    return [
      'MONGODB_URI is malformed and could not be parsed.',
      '  Expected: mongodb+srv://<user>:<password>@<cluster>.mongodb.net/',
    ]
  }

  if (/querySrv|ENOTFOUND|EAI_AGAIN/i.test(message)) {
    return [
      'DNS lookup for the cluster hostname failed.',
      '  1. Check the cluster hostname in MONGODB_URI is spelled correctly',
      '  2. Check this machine has working DNS / internet access',
    ]
  }

  return ['Could not connect to MongoDB. The full driver error follows.']
}

/**
 * Opens the connection. Throws if the database is unreachable.
 *
 * `dbName` is set explicitly rather than relying on the path segment of the
 * URI. Atlas's "Connect" dialog hands out a connection string with no database
 * in the path, and the driver then silently defaults to a database literally
 * called "test" — so the app would appear to work while writing to the wrong
 * place. Setting it here makes the target explicit and independent of however
 * the operator pasted their URI.
 */
export async function connectDatabase(
  uri: string = env.mongodbUri,
  dbName: string = env.mongodbDbName
): Promise<typeof mongoose> {
  return mongoose.connect(uri, {
    dbName,

    // Give up rather than hanging forever when Atlas is unreachable — the most
    // common cause is this machine's IP missing from the cluster allowlist.
    serverSelectionTimeoutMS: 10_000,
    socketTimeoutMS: 45_000,

    maxPoolSize: env.isProduction ? 20 : 10,
    minPoolSize: 0,

    // Never let Mongoose create indexes implicitly on first write. Index
    // creation is an explicit, observable step (`npm run db:indexes`) so it
    // cannot silently block a production request.
    autoIndex: false,
    autoCreate: false,
  })
}

/** Closes the connection. Used by graceful shutdown and by the test teardown. */
export async function disconnectDatabase(): Promise<void> {
  await mongoose.connection.close()
}

/** True when the connection is open and usable. */
export function isDatabaseConnected(): boolean {
  return mongoose.connection.readyState === 1
}

export { mongoose }
